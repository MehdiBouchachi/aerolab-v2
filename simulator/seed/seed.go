// Package seed provisions a DEV-ONLY environment: per-device MQTT
// credentials, a topic ACL and a Mosquitto configuration. Everything is
// written under an ignored directory (.dev/) with random secrets; nothing
// secret is ever committed. Seeded sites/units are explicitly SIMULATED.
package seed

import (
	"crypto/pbkdf2"
	"crypto/rand"
	"crypto/sha512"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"os/user"
	"path/filepath"
	"strconv"
	"strings"

	mc "github.com/mehdibouchachi/aerolab-v2/contracts/mqtt"
)

const EdgeMQTTUser = "aerolab-edge"

type Options struct {
	OutDir     string // e.g. .dev
	SiteID     string
	Devices    int
	BrokerHost string // bind address, default 127.0.0.1
	BrokerPort int    // default 18830 (avoid clashing with a system broker)
}

type DeviceCred struct {
	DeviceID string `json:"device_id"`
	UnitID   string `json:"unit_id"`
	Password string `json:"password"`
}

type Result struct {
	OutDir        string
	SiteID        string
	Devices       []DeviceCred
	EdgePassword  string
	AdminUser     string
	AdminPassword string
	BrokerURL     string
	MosquittoConf string
	CredsFile     string
	EdgeEnvFile   string
}

// HashPBKDF2 returns a Mosquitto 2.x "$7$" password hash
// (PBKDF2-HMAC-SHA512, 101 iterations, 12-byte salt).
func HashPBKDF2(password string) (string, error) {
	salt := make([]byte, 12)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}
	return hashWithSalt(password, salt)
}

func hashWithSalt(password string, salt []byte) (string, error) {
	const iter = 101
	dk, err := pbkdf2.Key(sha512.New, password, salt, iter, 64)
	if err != nil {
		return "", err
	}
	return fmt.Sprintf("$7$%d$%s$%s", iter, base64.StdEncoding.EncodeToString(salt), base64.StdEncoding.EncodeToString(dk)), nil
}

func secret(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return hex.EncodeToString(b)
}

// DeviceID / UnitID naming used by the simulator and tests.
func DeviceID(i int) string { return fmt.Sprintf("esp32-sim-%03d", i) }
func UnitID(i int) string   { return fmt.Sprintf("unit-sim-%03d", i) }

// ACL returns the broker ACL. Device rules use %u (username == device_id) so
// ONE static ACL enforces per-device topic isolation for any N.
func ACL() string {
	var b strings.Builder
	b.WriteString("# GENERATED by aerolab-seed (dev). Per-device isolation via %u.\n")
	b.WriteString("# Edge service account: read device uploads, write commands + receipts.\n")
	fmt.Fprintf(&b, "user %s\n", EdgeMQTTUser)
	for _, l := range mc.DeviceUploadLeaves {
		fmt.Fprintf(&b, "topic read aerolab/v1/devices/+/%s\n", l)
	}
	for _, l := range mc.DeviceDownloadLeaves {
		fmt.Fprintf(&b, "topic write aerolab/v1/devices/+/%s\n", l)
	}
	b.WriteString("\n# Every other user is a device and may only touch its OWN topics.\n")
	for _, l := range mc.DeviceUploadLeaves {
		fmt.Fprintf(&b, "pattern write aerolab/v1/devices/%%u/%s\n", l)
	}
	for _, l := range mc.DeviceDownloadLeaves {
		fmt.Fprintf(&b, "pattern read aerolab/v1/devices/%%u/%s\n", l)
	}
	return b.String()
}

func MosquittoConf(dir, host string, port int) string {
	return fmt.Sprintf(`# GENERATED by aerolab-seed. DEV ONLY - plain MQTT on a loopback listener.
# Production Pi config lives in infrastructure/raspberry-pi/mosquitto.
listener %d %s
allow_anonymous false
password_file %s
acl_file %s
persistence false
max_packet_size %d
max_connections 128
max_queued_messages 200
max_inflight_messages 20
memory_limit 67108864
connection_messages false
log_dest stdout
log_type error
log_type warning
`, port, host, filepath.Join(dir, "mosquitto", "passwd"), filepath.Join(dir, "mosquitto", "acl"), 16*1024)
}

// Provision writes the full dev environment and returns what it created.
func Provision(o Options) (*Result, error) {
	if o.BrokerHost == "" {
		o.BrokerHost = "127.0.0.1"
	}
	if o.BrokerPort == 0 {
		o.BrokerPort = 18830
	}
	if o.SiteID == "" {
		o.SiteID = "site-sim-01"
	}
	if !mc.ValidID(o.SiteID) {
		return nil, fmt.Errorf("invalid site id %q", o.SiteID)
	}
	if o.Devices < 1 || o.Devices > 64 {
		return nil, fmt.Errorf("devices must be 1..64")
	}
	abs, err := filepath.Abs(o.OutDir)
	if err != nil {
		return nil, err
	}
	mdir := filepath.Join(abs, "mosquitto")
	if err := os.MkdirAll(mdir, 0o700); err != nil {
		return nil, err
	}
	res := &Result{OutDir: abs, SiteID: o.SiteID, EdgePassword: secret(16), AdminUser: "admin", AdminPassword: secret(10),
		BrokerURL: fmt.Sprintf("tcp://%s:%d", o.BrokerHost, o.BrokerPort)}

	var pw strings.Builder
	h, err := HashPBKDF2(res.EdgePassword)
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&pw, "%s:%s\n", EdgeMQTTUser, h)
	for i := 1; i <= o.Devices; i++ {
		c := DeviceCred{DeviceID: DeviceID(i), UnitID: UnitID(i), Password: secret(16)}
		h, err := HashPBKDF2(c.Password)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&pw, "%s:%s\n", c.DeviceID, h)
		res.Devices = append(res.Devices, c)
	}
	write := func(path, content string, mode os.FileMode) error { return os.WriteFile(path, []byte(content), mode) }
	if err := write(filepath.Join(mdir, "passwd"), pw.String(), 0o600); err != nil {
		return nil, err
	}
	if err := write(filepath.Join(mdir, "acl"), ACL(), 0o600); err != nil {
		return nil, err
	}
	res.MosquittoConf = filepath.Join(mdir, "mosquitto.conf")
	if err := write(res.MosquittoConf, MosquittoConf(abs, o.BrokerHost, o.BrokerPort), 0o600); err != nil {
		return nil, err
	}
	creds, _ := json.MarshalIndent(map[string]any{"site_id": o.SiteID, "broker_url": res.BrokerURL, "devices": res.Devices}, "", "  ")
	res.CredsFile = filepath.Join(abs, "devices.json")
	if err := write(res.CredsFile, string(creds)+"\n", 0o600); err != nil {
		return nil, err
	}
	env := fmt.Sprintf("# GENERATED dev secrets - never commit.\nAEROLAB_SITE_ID=%s\nAEROLAB_SITE_NAME=AeroLab-DEV-SIMULATED\nAEROLAB_MQTT_URL=%s\nAEROLAB_MQTT_USER=%s\nAEROLAB_MQTT_PASSWORD=%s\nAEROLAB_ALLOW_SIMULATED_DATA=true\nAEROLAB_DB_PATH=%s\nAEROLAB_BOOTSTRAP_ADMIN_USER=%s\nAEROLAB_BOOTSTRAP_ADMIN_PASSWORD=%s\nAEROLAB_PROVISION_FILE=%s\n",
		o.SiteID, res.BrokerURL, EdgeMQTTUser, res.EdgePassword, filepath.Join(abs, "aerolab.db"), res.AdminUser, res.AdminPassword, res.CredsFile)
	res.EdgeEnvFile = filepath.Join(abs, "edge.env")
	if err := write(res.EdgeEnvFile, env, 0o600); err != nil {
		return nil, err
	}
	if err := fixBrokerOwnership(mdir); err != nil {
		return nil, err
	}
	return res, nil
}

// When provisioning runs as root (containers, CI) Mosquitto drops to the
// "mosquitto" user and must be able to read its own config. Secrets stay
// 0600 and owned by that user; no-op for normal users.
func fixBrokerOwnership(mdir string) error {
	if os.Geteuid() != 0 {
		return nil
	}
	u, err := user.Lookup("mosquitto")
	if err != nil {
		return nil // no such user: broker will run as root-less dev user
	}
	uid, _ := strconv.Atoi(u.Uid)
	gid, _ := strconv.Atoi(u.Gid)
	// the directory chain must be traversable by the broker user
	for d := mdir; d != "/" && d != "."; d = filepath.Dir(d) {
		if fi, err := os.Stat(d); err == nil && fi.Mode().Perm()&0o001 == 0 {
			_ = os.Chmod(d, fi.Mode().Perm()|0o711)
		}
	}
	entries, _ := os.ReadDir(mdir)
	_ = os.Chown(mdir, uid, gid)
	for _, e := range entries {
		if err := os.Chown(filepath.Join(mdir, e.Name()), uid, gid); err != nil {
			return err
		}
	}
	return nil
}
